"""Check the static VPM release and compatibility with cached published metadata.

Run with: python3 -m unittest discover -s tests -v
The listing and ZIP are generated by VRCForward's tools/vpm-listing.py and
tools/package-release.py. Published archives must remain immutable, including
documentation: VPM clients can retain an earlier index and verify its checksum.
"""
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path, PurePosixPath
import stat
import unittest
from urllib.parse import parse_qs, urlsplit
import zipfile


ROOT = Path(__file__).resolve().parents[1]


def versions(listing):
    for name, package in listing['packages'].items():
        for version, manifest in package['versions'].items():
            yield name, version, manifest


def archive_path(manifest):
    url = urlsplit(manifest['url'])
    base = urlsplit(json.loads((ROOT / 'index.json').read_text())['url'])
    if url.scheme != base.scheme or url.netloc != base.netloc:
        raise ValueError('Package URL must use this listing site')
    filename = PurePosixPath(url.path).relative_to(PurePosixPath(base.path).parent)
    if '..' in filename.parts:
        raise ValueError('Package URL must remain inside the listing directory')
    return ROOT / filename


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs = []

    def handle_starttag(self, tag, attrs):
        if tag == 'a':
            self.hrefs.extend(value for key, value in attrs if key == 'href')


class ListingTests(unittest.TestCase):
    def setUp(self):
        self.listing = json.loads((ROOT / 'index.json').read_text())

    def test_first_published_listing_still_downloads_matching_bytes(self):
        # ec49d5f was publicly deployed by Pages run 39750465647 before 292f0b7.
        # Keep this fixture unchanged so a repack cannot invalidate cached indexes.
        cached = json.loads((ROOT / 'tests/fixtures/published-0.3.0.json').read_text())
        for name, version, manifest in versions(cached):
            with self.subTest(package=name, version=version):
                payload = archive_path(manifest).read_bytes()
                self.assertEqual(hashlib.sha256(payload).hexdigest(), manifest['zipSHA256'],
                                 'A client using the published index rejects this download')
                current = self.listing['packages'][name]['versions'][version]
                self.assertEqual(current['zipSHA256'], manifest['zipSHA256'])

    def test_current_listing_and_archive_agree(self):
        for name, version, manifest in versions(self.listing):
            with self.subTest(package=name, version=version):
                path = archive_path(manifest)
                self.assertEqual(path.name, f'{name}-{version}.zip')
                self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), manifest['zipSHA256'])
                with zipfile.ZipFile(path) as archive:
                    self.assertIsNone(archive.testzip())
                    package = json.loads(archive.read('package.json'))
                self.assertEqual(package['name'], name)
                self.assertEqual(package['version'], version)
                self.assertEqual(package, {k: v for k, v in manifest.items() if k not in {'url', 'zipSHA256'}})

    def test_archives_have_safe_unique_files(self):
        for name, version, manifest in versions(self.listing):
            with self.subTest(package=name, version=version):
                with zipfile.ZipFile(archive_path(manifest)) as archive:
                    entries = archive.infolist()
                    self.assertEqual(len(entries), len({entry.filename for entry in entries}))
                    for entry in entries:
                        path = PurePosixPath(entry.filename)
                        self.assertFalse(path.is_absolute())
                        self.assertNotIn('..', path.parts)
                        self.assertNotIn('\\', entry.filename)
                        self.assertTrue(stat.S_ISREG(entry.external_attr >> 16))

    def test_landing_page_adds_the_advertised_repository(self):
        page = (ROOT / 'index.html').read_text()
        parser = Links()
        parser.feed(page)
        add_links = [urlsplit(url) for url in parser.hrefs if url.startswith('vcc:')]
        self.assertEqual(len(add_links), 1)
        link = add_links[0]
        self.assertEqual((link.netloc, link.path), ('vpm', '/addRepo'))
        self.assertEqual(parse_qs(link.query), {'url': [self.listing['url']]})
        self.assertIn(self.listing['url'], page)
        for _, version, manifest in versions(self.listing):
            self.assertIn(f"{manifest['displayName']} {version}", page)


if __name__ == '__main__':
    unittest.main()
